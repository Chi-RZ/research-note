#!/usr/bin/env python3
"""Regenerate the two rosters — never hand-edit either.

project_memory/_index.md  three sections: one row per node (number · name ·
                          one-liner; the number is assigned once, here, and
                          preserved across regeneration — it is the `<nn>` of
                          every entry id on that node — and never reused),
                          one row per entry (id · name · status), and one row
                          per objective (id · page · status · verdict line) —
                          the registry the next free `O<nn>` is read from.
src/INDEX.md              one row per capability: name · where it lives ·
                          docstring first line. The discovery rule reads this
                          before any new code is written.

Usage: python3 <plugin>/scripts/gen_index.py
"""
from __future__ import annotations

import ast
import re
import sys
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from projroot import nth_parent, resolve_root  # noqa: E402

ROOT = resolve_root(nth_parent(Path(__file__), 2))
NODES = ROOT / "project_memory" / "nodes"
OBJECTIVES = ROOT / "project_memory" / "objectives"
INDEX = ROOT / "project_memory" / "_index.md"
SRC = ROOT / "src"
SRC_INDEX = SRC / "INDEX.md"

#: An existing roster row: `| 07 | [name](nodes/name/node.md) | ... |`.
ROSTER_ROW_RE = re.compile(r"^\|\s*(\d+)\s*\|\s*\[`?([A-Za-z0-9_.-]+)`?\]", re.M)

HEADER = """# Roster

GENERATED by the research-note plugin's `scripts/gen_index.py` — never
hand-edit; fix the node or the page and regenerate. Node numbers (the `<nn>`
of every entry id) are assigned once and never reused.

| # | node | what it is |
|---|------|------------|
"""

ENTRIES_HEADER = """
## Entries

| id | entry | status |
|---|---|---|
"""

OBJECTIVES_HEADER = """
## Objectives

O numbers are assigned once, read from here (the next free one), never reused.

| id | objective | status | verdict |
|---|---|---|---|
"""

SRC_HEADER = """# src index

One row per capability. GENERATED by the research-note plugin's
`scripts/gen_index.py` — never hand-edit. The discovery rule (root CLAUDE.md)
reads this before any new code is written.
{domain}
| capability | lives at | what it does |
|------------|----------|--------------|
"""


def _domain_libs() -> str:
    """The `## Domain libraries` line, from hpc.env's `LIB_<name>_LOCAL`
    declarations — so the discovery rule's step 0 (check the domain library
    first) has its pointer.

    LOCAL, and not `lib_path_here`'s "the first declared path that exists on
    this machine": INDEX.md is a COMMITTED generated file, so a line resolved
    per machine flips every time the other side regenerates, and the diff
    reads as a capability change. LOCAL is the record-keeping machine's column
    — the one whoever reads this file is standing on.

    The legacy DOMAIN_LIBS / DOMAIN_LIB_DIR spellings are the fallback, as
    everywhere else, and only when no LIB_* line is declared. Reading solely
    those is what made this function go silent the moment a project migrated:
    the section vanished from INDEX.md on the next regeneration, taking with it
    the pointer the root contract tells every agent to read before writing
    anything new.
    """
    conf = ""
    for f in (ROOT / ".claude" / "hpc.env", ROOT / ".claude" / "hpc.local.env"):
        if f.exists():
            conf += f.read_text(encoding="utf-8")
    paths = [m.group(1).strip() for m
             in re.finditer(r"^\s*LIB_\w+_LOCAL=\"?([^\"\n]+)", conf, re.M)]
    if not paths:
        m = (re.search(r"^\s*DOMAIN_LIBS=\"?([^\"\n]+)", conf, re.M)
             or re.search(r"^\s*DOMAIN_LIB_DIR=\"?([^\"\n]+)", conf, re.M))
        paths = [m.group(1).strip()] if m else []
    if not paths:
        return ""
    listed = ", ".join(f"`{q}`" for q in dict.fromkeys(paths))
    return (f"\n## Domain libraries\n\n{listed} — check these "
            f"before writing anything new.\n")


def one_liner(name: str) -> str:
    """The node's impl DESCRIPTION, where a Python impl declares one.

    Read with `ast` rather than a regex: a description long enough to be worth
    reading is usually written as the parenthesised implicit concatenation
    Python offers for exactly that, and a pattern anchored on a closing quote at
    end of line sees none of it — it silently yields the em dash, so the roster
    column empties without anything failing. Parsing the assignment instead
    accepts every spelling (one line, parenthesised, triple-quoted) and ignores
    a DESCRIPTION that is not a module-level string literal.
    """
    impl = ROOT / "experiments" / name / "impl" / "__init__.py"
    if not impl.exists():
        return "—"
    src = impl.read_text(encoding="utf-8")
    try:
        for node in ast.parse(src).body:
            if not isinstance(node, ast.Assign):
                continue
            if not any(isinstance(t, ast.Name) and t.id == "DESCRIPTION"
                       for t in node.targets):
                continue
            if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                return " ".join(node.value.value.split())
    except SyntaxError:
        pass
    # An impl that does not parse (a Julia shim, a partial edit) still answers
    # the simple spelling, so the roster degrades rather than breaking.
    m = re.search(r'^DESCRIPTION\s*=\s*["\'](.+?)["\']\s*$', src, re.M)
    return m.group(1) if m else "—"


def gen_node_roster() -> None:
    numbers: dict[str, int] = {}
    if INDEX.exists():
        numbers = {m.group(2): int(m.group(1))
                   for m in ROSTER_ROW_RE.finditer(INDEX.read_text(encoding="utf-8"))}
    on_disk = sorted(p.parent.name for p in NODES.glob("*/node.md"))
    nxt = max(numbers.values(), default=0) + 1
    for name in on_disk:
        if name not in numbers:
            numbers[name] = nxt
            nxt += 1
    rows = [f"| {numbers[n]:02d} | [`{n}`](nodes/{n}/node.md) | {one_liner(n)} |"
            for n in sorted(on_disk, key=lambda n: numbers[n])]

    # the entry roster: every entry on every page, sorted by id — read-first
    # starts from this one file
    entries = []
    for page in sorted(NODES.rglob("*.md")):
        t = page.read_text(encoding="utf-8")
        heads = list(re.finditer(r"^#{2,4}\s+Entry:\s*(.+?)\s*$", t, re.M))
        for i, m in enumerate(heads):
            end = heads[i + 1].start() if i + 1 < len(heads) else len(t)
            body = t[m.end():end]
            eid = re.search(r"^(?:-\s+\*\*)?Id:(?:\*\*)?\s*(\S+)", body, re.M)
            st = re.search(r"^(?:-\s+\*\*)?Status:(?:\*\*)?\s*(\S+)", body, re.M)
            slug = re.sub(r"[^\w\s-]", "", ("Entry: " + m.group(1)).lower())
            slug = re.sub(r"\s+", "-", slug.strip())
            rel = page.relative_to(NODES.parent).as_posix()
            entries.append((eid.group(1) if eid else "??",
                            f"| {eid.group(1) if eid else '??'} | "
                            f"[{m.group(1)}]({rel}#{slug}) | "
                            f"{st.group(1) if st else '?'} |"))
    entries.sort(key=lambda e: e[0])

    # the objective roster: read-first sees the goals, not just the nodes —
    # an agent deciding what to run next reads which objectives are active and
    # what each currently answers. The id is assigned on the page (frontmatter),
    # not here; this section is where the next free O<nn> is READ from, and the
    # linter's O12 refuses a duplicate.
    objs = []
    for page in sorted(OBJECTIVES.glob("*.md")):
        t = page.read_text(encoding="utf-8")
        oid = re.search(r"^id:\s*(\S+)", t, re.M)
        st = re.search(r"^status:\s*(\S+)", t, re.M)
        att = re.search(r"^attention:\s*(.+?)\s*$", t, re.M)
        vm = re.search(r"^##\s+Verdict\s*\n+(.+?)\s*$", t, re.M)
        # bold markers off: the snippet cuts mid-sentence, so a `**` pair the
        # page balances is unbalanced here and renders as literal asterisks
        verdict = " ".join(vm.group(1).split()).replace("**", "") if vm else "—"
        if len(verdict) > 100:
            verdict = verdict[:97] + "…"
        status = st.group(1) if st else "?"
        if att:
            status += " ⚠"
        objs.append((oid.group(1) if oid else "??",
                     f"| {oid.group(1) if oid else '??'} | "
                     f"[{page.stem}](objectives/{page.name}) | {status} | {verdict} |"))
    objs.sort(key=lambda o: o[0])

    INDEX.write_text(HEADER + "\n".join(rows) + "\n"
                     + ENTRIES_HEADER + "\n".join(r for _, r in entries) + "\n"
                     + (OBJECTIVES_HEADER + "\n".join(r for _, r in objs) + "\n"
                        if objs else ""),
                     encoding="utf-8")
    print(f"_index.md: {len(on_disk)} node(s), {len(entries)} entr(y/ies), "
          f"{len(objs)} objective(s) — {INDEX}")


def gen_src_index(check: bool = False) -> bool:
    if not SRC.is_dir():
        return
    rows = []
    for py in sorted(SRC.rglob("*.py")):
        if py.name.startswith("_"):
            continue
        rel = py.relative_to(ROOT)
        try:
            # Silence the file's own SyntaxWarnings (an invalid escape in a
            # docstring, say). They are the SOURCE's business, not this
            # roster's, and --check runs on every commit that touches src/ —
            # a gate that prints a screen of unrelated warnings is a gate
            # people learn to scroll past.
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                tree = ast.parse(py.read_text(encoding="utf-8"))
        except SyntaxError:
            rows.append(f"| — | `{rel}` | (does not parse) |")
            continue
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                                     ast.ClassDef)):
                continue
            if node.name.startswith("_"):
                continue
            doc = (ast.get_docstring(node) or "").strip().splitlines()
            rows.append(f"| `{node.name}` | `{rel}` | {doc[0] if doc else '—'} |")
    text = (SRC_HEADER.format(domain=_domain_libs())
            + "\n".join(rows) + ("\n" if rows else ""))
    if check:
        # The generator IS the verifier — there is no second implementation to
        # drift. Stale means: src/ has capabilities this file does not list, so
        # the discovery rule ("read src/INDEX.md before writing anything new")
        # silently stops finding them and the next agent writes a duplicate.
        if SRC_INDEX.exists() and SRC_INDEX.read_text(encoding="utf-8") == text:
            return True
        have = sum(1 for ln in (SRC_INDEX.read_text(encoding="utf-8").split("\n")
                                if SRC_INDEX.exists() else [])
                   if ln.startswith("| `"))
        print(f"gen_index: src/INDEX.md is STALE — it lists {have} "
              f"capabilit(y/ies), src/ has {len(rows)}. Run "
              f"`gen_index.py --src` IN THE MAIN CHECKOUT (a worktree is "
              f"sparse and generates a short index).", file=sys.stderr)
        return False
    SRC_INDEX.write_text(text, encoding="utf-8")
    print(f"src/INDEX.md: {len(rows)} capabilit(y/ies) — {SRC_INDEX}")
    return True


def main() -> None:
    """`--record` regenerates only project_memory/_index.md, `--src` only
    src/INDEX.md; neither means both, which is how every caller ran it before
    the split. The split exists for the record bus: it commits under
    `memory:`, a prefix the commit-msg hook forbids from touching src/, so it
    has to be able to ask for the record roster alone."""
    want = set(sys.argv[1:])
    check = "--check" in want
    want.discard("--check")
    unknown = want - {"--record", "--src"}
    if unknown:
        print(f"gen_index.py: unknown option(s) {' '.join(sorted(unknown))} — "
              f"pass --record, --src, --check, both, or neither (neither = both)",
              file=sys.stderr)
        raise SystemExit(2)
    if check:
        # --check verifies src/INDEX.md only. The record roster is committed
        # through the bus, which regenerates it as part of the write; src/ has
        # no such door — its index is a separate step after a branch lands, in
        # a different checkout from the work, and skipping it fails nothing.
        raise SystemExit(0 if gen_src_index(check=True) else 1)
    if not want or "--record" in want:
        gen_node_roster()
    if not want or "--src" in want:
        gen_src_index()


if __name__ == "__main__":
    main()
